//! FinTS codec: wire syntax, data element types and declarative segments.
//!
//! - [`wire`]: tokenizer and serializer for the FinTS syntax (Formals H.1),
//!   ISO 8859-1, panic-free.
//! - [`types`]: the data element formats (Formals B.4): [`An`], [`Num`],
//!   [`Dig`], [`Jn`], [`Dat`], [`Tim`], [`Cur`], [`Wrt`], [`Btg`], [`Bin`],
//!   [`Id`], [`Code`].
//! - [`Segment`] / [`DataElementGroup`] derives: one struct per segment
//!   version or group, generating parse and serialise. Definitions live in
//!   [`defs`]; [`registry`] lists them for lookup by (code, version).
//! - [`schema`]: a static description of every definition
//!   ([`SegmentDef::schema`]), generated by the derives.
//! - Raw fallback: [`parse_message`] / [`parse_segment`] give
//!   [`ParsedSegment::Typed`], or [`ParsedSegment::Raw`] with the
//!   tokenized segment and the [`CodecError`] that kept it from being typed.
//!
//! How to add a segment: `docs/codec.md`.

