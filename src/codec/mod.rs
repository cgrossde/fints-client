/// Attribute misuse that must not compile.
///
/// An open repetition that is not the last element of its group:
///
/// ```compile_fail
/// use fints_client::codec::{An, DataElementGroup};
/// #[derive(DataElementGroup)]
/// struct Bad { list: Vec<An>, after: An }
/// ```
///
/// A group that ends in an open repetition, nested before another element:
///
/// ```compile_fail
/// use fints_client::codec::{An, DataElementGroup};
/// #[derive(DataElementGroup)]
/// struct Open { #[de(min_count = 1)] list: Vec<An> }
/// #[derive(DataElementGroup)]
/// struct Bad { open: Open, after: An }
/// ```
///
/// A repeated segment element without `max_count` that is not the last:
///
/// ```compile_fail
/// use fints_client::codec::{An, Segment};
/// #[derive(Segment)]
/// #[segment(code = "XBAD", version = 1)]
/// struct Bad { list: Vec<An>, after: An }
/// ```
///
/// A length rule on a group:
///
/// ```compile_fail
/// use fints_client::codec::{Btg, Segment};
/// #[derive(Segment)]
/// #[segment(code = "XBAD", version = 1)]
/// struct Bad { #[de(max = 3)] amount: Btg }
/// ```
///
/// Repetition counts on a field that is not a `Vec`, an unknown attribute,
/// both `max` and `len`, and a missing `#[segment]`:
///
/// ```compile_fail
/// use fints_client::codec::{An, Segment};
/// #[derive(Segment)]
/// #[segment(code = "XBAD", version = 1)]
/// struct Bad { #[de(max_count = 2)] one: An }
/// ```
///
/// ```compile_fail
/// use fints_client::codec::{An, Segment};
/// #[derive(Segment)]
/// #[segment(code = "XBAD", version = 1)]
/// struct Bad { #[de(maximum = 2)] one: An }
/// ```
///
/// ```compile_fail
/// use fints_client::codec::{An, Segment};
/// #[derive(Segment)]
/// #[segment(code = "XBAD", version = 1)]
/// struct Bad { #[de(max = 2, len = 2)] one: An }
/// ```
///
/// ```compile_fail
/// use fints_client::codec::{An, Segment};
/// #[derive(Segment)]
/// struct Bad { one: An }
/// ```
///
/// The same definitions written correctly compile:
///
/// ```
/// use fints_client::codec::{An, Btg, DataElementGroup, Segment};
/// #[derive(DataElementGroup)]
/// struct Good { after: An, list: Vec<An> }
/// #[derive(Segment)]
/// #[segment(code = "XGOOD", version = 1)]
/// struct GoodSeg { #[de(max_count = 3)] list: Vec<An>, amount: Btg, #[de(max = 2)] one: An }
/// ```
